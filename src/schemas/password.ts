/*
  비밀번호 규칙. 마이페이지의 변경 폼과 관리자 콘솔의 계정 폼이 함께 지킨다 —
  한쪽에만 두면 다른 화면이 그 폴더를 넘겨다봐야 한다.

  서버도 같은 규칙을 본다 (`UserAddInfo.password` 의 pattern). 화면이 더 느슨하면
  통과시킨 뒤 서버에서 되돌아오고, 더 빡빡하면 서버가 받는 비밀번호를 화면이 막는다.
*/

/** 영대문자·영소문자·숫자·특수문자를 각 하나 이상, 공백 없이 8~20자. */
export const PASSWORD_RULE = /^(?=.*[a-z])(?=.*[A-Z])(?=.*[0-9])(?=.*[^A-Za-z0-9\s])(?=\S+$).{8,20}$/;

/** 폼 힌트와 오류 문구가 갈리지 않게 규칙을 한 문장으로 적어 둔다 */
export const PASSWORD_HINT = '영대문자·소문자·숫자·특수문자 각 1개 이상, 8~20자';
